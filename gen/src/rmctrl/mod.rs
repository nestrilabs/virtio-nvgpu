//! RM controls whose parameters carry a pointer RM dereferences.
//!
//! An `NV_ESC_RM_CONTROL`'s parameter block is a flat struct for almost every
//! command. For the ones listed here it is not: the block holds an `NvP64`,
//! and RM copies `count * element size` bytes through it from the *caller's*
//! address space before the control runs, and back afterwards
//! (`embeddedParamCopyIn`/`Out` in NVIDIA's open-gpu-kernel-modules).
//!
//! Through this project the caller is the backend. A guest's value in that
//! field is an address RM reads and writes in the backend's memory. The tables
//! here say, per driver release, where each pointer sits, how its length is
//! derived, and which direction it is copied, so the backend can supply every
//! such buffer itself and never let a guest's address reach RM.
//!
//! Generated by `gen/rmctrl_extract.py`, which compiles a probe against each
//! release's own control headers. Nothing here is transcribed by hand.
//!
//! # What is refused
//!
//! An entry with `refuse` set is a control the generator could not describe:
//! its case does not use the macro the parser reads, or it compiles into RM
//! only under a build flag the published headers do not settle
//! (`USE_AMAPLIB`). Whether RM dereferences a pointer in it is then unknown,
//! so the backend answers it `NV_ERR_NOT_SUPPORTED` rather than forwarding it.
//! A control absent from the table entirely is one RM does no embedded copy
//! for, and is forwarded as it always was.

pub mod v535_129_03;
pub mod v580_178_04;
pub mod v595_71_05;
pub mod v595_104_02;
pub mod v615_71_09;

use crate::version::DriverVersion;

/// The most bytes one embedded pointer may address.
///
/// The length is derived from a count field inside the guest's own parameters,
/// at an offset from a table generated for one release. A guest that writes a
/// large number there, or a release whose field moved, must not turn into a
/// large allocation in the backend: over this, the control is refused.
///
/// Nothing RM copies this way is big. The largest in any table is a class list
/// of a few thousand `NvU32`, and the P2P caps matrix at 32 x 32 words.
pub const MAX_EMBEDDED_BYTES: usize = 1 << 20;

/// How many elements an embedded pointer addresses.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Count {
    /// A constant, from the call site in RM.
    Fixed(u64),
    /// Read from a field of the parameter block.
    Field { offset: usize, width: usize },
    /// Read from a field and squared: `NV0000_CTRL_CMD_SYSTEM_GET_P2P_CAPS`
    /// addresses a `gpuCount` x `gpuCount` matrix.
    Squared { offset: usize, width: usize },
}

impl Count {
    /// The element count for one call, read out of its parameter block.
    ///
    /// `None` when the field lies outside the block, or when the width is not
    /// one the generator emits -- both of which mean the table and the block
    /// disagree, and the caller must refuse rather than guess.
    pub fn elements(self, params: &[u8]) -> Option<u64> {
        let read = |offset: usize, width: usize| -> Option<u64> {
            let end = offset.checked_add(width)?;
            let b = params.get(offset..end)?;
            Some(match width {
                1 => b[0] as u64,
                2 => u16::from_le_bytes(b.try_into().ok()?) as u64,
                4 => u32::from_le_bytes(b.try_into().ok()?) as u64,
                8 => u64::from_le_bytes(b.try_into().ok()?),
                _ => return None,
            })
        };
        match self {
            Count::Fixed(n) => Some(n),
            Count::Field { offset, width } => read(offset, width),
            Count::Squared { offset, width } => {
                let n = read(offset, width)?;
                n.checked_mul(n)
            }
        }
    }
}

/// One pointer inside a control's parameter block.
#[derive(Clone, Copy, Debug)]
pub struct EmbeddedPtr {
    /// Where the `NvP64` sits in the parameter block.
    pub ptr_offset: usize,
    pub count: Count,
    pub elem_size: usize,
    /// RM reads the caller's buffer before the control runs.
    pub copy_in: bool,
    /// RM writes it back afterwards.
    pub copy_out: bool,
}

impl EmbeddedPtr {
    /// How many bytes this pointer addresses for one call.
    ///
    /// `None` when the count cannot be read, or the product overflows, or the
    /// result is over [`MAX_EMBEDDED_BYTES`]. Zero is a real answer: RM's own
    /// code treats a zero count as "no copy", and so does the backend.
    pub fn bytes(&self, params: &[u8]) -> Option<usize> {
        let n = self.count.elements(params)?;
        let bytes = n.checked_mul(self.elem_size as u64)?;
        let bytes = usize::try_from(bytes).ok()?;
        (bytes <= MAX_EMBEDDED_BYTES).then_some(bytes)
    }
}

/// One control, as one driver release lays it out.
pub struct RmCtrlEntry {
    /// The `NVXXXX_CTRL_CMD_*` value, as it arrives in `NVOS54.cmd`.
    pub cmd: u32,
    /// `sizeof` the parameter struct. Zero on a refused entry.
    pub params_size: usize,
    pub ptrs: &'static [EmbeddedPtr],
    /// The generator could not describe this control. Refuse it.
    pub refuse: bool,
}

struct Profile {
    version: DriverVersion,
    /// A function rather than the slice itself, as in `versions`: a static
    /// read in another static's initializer is const-evaluated, and the
    /// generated table can end up copied per use rather than shared. Read at
    /// run time there is one of each.
    table: fn() -> &'static [RmCtrlEntry],
}

/// Profiles in ascending version order.
static PROFILES: &[Profile] = &[
    Profile {
        version: DriverVersion::new(535, 129, 3),
        table: || v535_129_03::TABLE,
    },
    Profile {
        version: DriverVersion::new(580, 178, 4),
        table: || v580_178_04::TABLE,
    },
    Profile {
        version: DriverVersion::new(595, 71, 5),
        table: || v595_71_05::TABLE,
    },
    Profile {
        version: DriverVersion::new(595, 104, 2),
        table: || v595_104_02::TABLE,
    },
    Profile {
        version: DriverVersion::new(615, 71, 9),
        table: || v615_71_09::TABLE,
    },
];

/// The table for a host driver version: its own, or the nearest older one.
///
/// Nearest-older is what the ioctl tables do, and it is safe here for the same
/// reason it is not safe for UVM: every number this table supplies is checked
/// against the parameter block the guest actually sent before it is used, and a
/// count that does not fit refuses the call rather than sizing a buffer.
pub fn table_for(v: DriverVersion) -> Option<&'static [RmCtrlEntry]> {
    PROFILES
        .iter()
        .rev()
        .find(|p| p.version <= v)
        .map(|p| (p.table)())
}

/// Look up one control. The tables are sorted by `cmd`, so this is a search.
pub fn lookup(table: &'static [RmCtrlEntry], cmd: u32) -> Option<&'static RmCtrlEntry> {
    table
        .binary_search_by_key(&cmd, |e| e.cmd)
        .ok()
        .map(|i| &table[i])
}

/// The versions with a table of their own, ascending.
pub fn supported_versions() -> impl Iterator<Item = DriverVersion> {
    PROFILES.iter().map(|p| p.version)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `lookup` is a binary search, so this is not a style point.
    #[test]
    fn every_table_is_sorted_and_has_no_duplicate() {
        for p in PROFILES {
            for w in (p.table)().windows(2) {
                assert!(
                    w[0].cmd < w[1].cmd,
                    "{}: {:#010x} then {:#010x}",
                    p.version,
                    w[0].cmd,
                    w[1].cmd
                );
            }
        }
    }

    #[test]
    fn a_refused_entry_describes_nothing() {
        for p in PROFILES {
            for e in (p.table)() {
                if e.refuse {
                    assert!(e.ptrs.is_empty(), "{}: {:#010x}", p.version, e.cmd);
                }
            }
        }
    }

    /// Every pointer has to sit inside the block it is read from, and address
    /// something. A table that says otherwise would refuse every call to the
    /// control at run time, silently.
    #[test]
    fn every_pointer_fits_its_parameter_block() {
        for p in PROFILES {
            for e in (p.table)().iter().filter(|e| !e.refuse) {
                for ptr in e.ptrs {
                    assert!(
                        ptr.ptr_offset + 8 <= e.params_size,
                        "{}: {:#010x} pointer at {} of {} bytes",
                        p.version,
                        e.cmd,
                        ptr.ptr_offset,
                        e.params_size
                    );
                    assert!(ptr.elem_size > 0, "{}: {:#010x}", p.version, e.cmd);
                    assert!(
                        ptr.copy_in || ptr.copy_out,
                        "{}: {:#010x} copies in neither direction",
                        p.version,
                        e.cmd
                    );
                    if let Count::Field { offset, width } | Count::Squared { offset, width } =
                        ptr.count
                    {
                        assert!(
                            offset + width <= e.params_size,
                            "{}: {:#010x} count at {offset}",
                            p.version,
                            e.cmd
                        );
                        assert!(matches!(width, 1 | 2 | 4 | 8));
                    }
                }
            }
        }
    }

    /// The control the guest driver carried by hand before this table existed:
    /// `NV0041_CTRL_CMD_GET_SURFACE_INFO`, a list of eight-byte entries whose
    /// count leads the block. It is the regression check that the generator
    /// reads the same layout the driver had hard-coded.
    #[test]
    fn get_surface_info_is_a_list_of_eight_byte_entries() {
        let t = table_for(DriverVersion::new(615, 71, 9)).expect("615 has a table");
        let e = lookup(t, 0x0041_0110).expect("GET_SURFACE_INFO is in the table");
        assert_eq!(e.ptrs.len(), 1);
        let p = e.ptrs[0];
        assert_eq!(p.ptr_offset, 8);
        assert_eq!(p.elem_size, 8);
        assert_eq!(p.count, Count::Field { offset: 0, width: 4 });

        // Three entries, as the leading count says.
        let mut params = vec![0u8; e.params_size];
        params[0..4].copy_from_slice(&3u32.to_le_bytes());
        assert_eq!(p.bytes(&params), Some(24));
    }

    /// A count a guest can write is a count a guest can lie about.
    #[test]
    fn an_impossible_count_refuses_rather_than_allocating() {
        let t = table_for(DriverVersion::new(615, 71, 9)).expect("615 has a table");
        let e = lookup(t, 0x0041_0110).expect("GET_SURFACE_INFO is in the table");
        let p = e.ptrs[0];

        let mut params = vec![0u8; e.params_size];
        params[0..4].copy_from_slice(&u32::MAX.to_le_bytes());
        assert_eq!(p.bytes(&params), None);

        // A block too short to hold the count field is refused, not read.
        assert_eq!(p.bytes(&[]), None);
    }

    #[test]
    fn a_zero_count_asks_for_nothing() {
        let t = table_for(DriverVersion::new(615, 71, 9)).expect("615 has a table");
        let e = lookup(t, 0x0041_0110).expect("GET_SURFACE_INFO is in the table");
        let params = vec![0u8; e.params_size];
        assert_eq!(e.ptrs[0].bytes(&params), Some(0));
    }

    /// `USE_AMAPLIB` is an RM build flag, so whether RM dereferences this
    /// control's pointers cannot be read off the headers. It must be present
    /// and refused, not absent: absent means forwarded.
    #[test]
    fn the_control_behind_a_build_flag_is_present_and_refused() {
        for v in supported_versions() {
            let t = table_for(v).expect("a listed version has a table");
            let e = lookup(t, 0x2080_1336).expect("FB_GET_AMAP_CONF is in every table");
            assert!(e.refuse, "{v}");
        }
    }

    #[test]
    fn a_version_between_tables_takes_the_lower_one() {
        let t = table_for(DriverVersion::new(600, 0, 0)).expect("falls back to 595.104.02");
        assert!(std::ptr::eq(t, v595_104_02::TABLE));
        assert!(table_for(DriverVersion::new(470, 0, 0)).is_none());
    }

    /// Squaring is where an overflow would hide: `gpuCount` is a `u32`.
    #[test]
    fn a_squared_count_cannot_overflow_into_a_small_number() {
        let c = Count::Squared {
            offset: 0,
            width: 4,
        };
        let params = u32::MAX.to_le_bytes().to_vec();
        assert_eq!(c.elements(&params), Some(18_446_744_065_119_617_025));
        let p = EmbeddedPtr {
            ptr_offset: 0,
            count: c,
            elem_size: 4,
            copy_in: false,
            copy_out: true,
        };
        assert_eq!(p.bytes(&params), None);
    }
}

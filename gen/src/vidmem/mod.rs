//! What a video memory limit needs to know about each RM release.
//!
//! Two jobs. *Counting*: which allocations take video memory, and how much --
//! `VID_HEAP_CONTROL` (NVOS32) allocations with `NVOS32_ATTR_LOCATION_VIDMEM`
//! and without `NVOS32_ALLOC_FLAGS_VIRTUAL`, and `NV01_MEMORY_LOCAL_USER`
//! allocations, whose parameters are `NV_MEMORY_ALLOCATION_PARAMS`.
//! *Telling*: what the guest is told the card holds. `FB_GET_INFO` answers a
//! list of indexed values, and `VID_HEAP_CONTROL` `INFO` a total, a free and a
//! largest free block. With a limit, all of them have to agree with it and
//! with each other, or an application works out a negative free space.
//!
//! Generated by `gen/vidmem_extract.py`, which reads each release's headers
//! and compiles a probe against them. The index numbers move between releases
//! -- `HEAP_RECLAIMABLE` is absent before 595.104.02 here, and was 0x3c on
//! 595.99.02 against 0x44 on 615.71.09 -- so nothing is carried from one
//! release to another.
//!
//! # Two spellings of one question
//!
//! `FB_GET_INFO` (0x20801301) is in RM's deprecated-control table, which
//! rewrites it into `FB_GET_INFO_V2` (0x20801303). A guest can send either,
//! and NVIDIA's own userspace sends the first. V1 carries its list behind a
//! pointer; V2 carries it inline, `fb_info_max_list` entries long, a length
//! that differs by release.
//!
//! # A table from another release
//!
//! [`select`] falls back to the nearest older release, as the other tables
//! do, and says so in [`Selected::exact`]. Rewriting what a guest is told
//! from another release's index numbers writes into whichever field now
//! holds that number. Whoever rewrites should treat an inexact table as no
//! table.

pub mod v535_129_03;
pub mod v580_178_04;
pub mod v595_104_02;
pub mod v595_71_05;
pub mod v615_71_09;

use crate::version::DriverVersion;

/// What an FB_INFO index reports. Every value is in KiB.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Role {
    /// How much video memory there is. With a limit: at most the limit.
    Total,
    /// How much of it is free. With a limit: at most what the guest has left.
    Free,
    /// A carve-out RM keeps out of the heap.
    Reserved,
    /// Where something is, not how much.
    Position,
    /// The CPU's window onto video memory, not video memory.
    Bar1,
}

/// One FB_INFO index that reports video memory, or a window onto it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FbIndex {
    pub name: &'static str,
    pub index: u32,
    pub role: Role,
}

/// A parameter block that carries a list of `NV2080_CTRL_FB_INFO`: its size,
/// and where the count and the list (a pointer for V1, inline for V2) are.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct List {
    pub size: u32,
    pub count: u32,
    pub list: u32,
}

/// Where an allocation's fields are in its parameter block. `h_memory` is
/// `u32::MAX` where the block has none.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Alloc {
    pub h_memory: u32,
    pub flags: u32,
    pub attr: u32,
    pub size: u32,
    pub limit: u32,
}

/// One release's numbers. Offsets are in bytes from the start of the block.
#[derive(Debug)]
pub struct Layout {
    /// Every memory-reporting index this release has, classified.
    pub fb_info: &'static [FbIndex],
    /// Indices the generator classifies that this release does not have.
    pub fb_absent: &'static [&'static str],
    pub cmd_fb_get_info: u32,
    pub cmd_fb_get_info_v2: u32,
    pub fb_info_max_list: u32,
    pub fb_info_entry_size: u32,
    pub fb_info_entry_index: u32,
    pub fb_info_entry_data: u32,
    pub fb_get_info_v1: List,
    pub fb_get_info_v2: List,
    pub nvos32_size: u32,
    pub nvos32_function: u32,
    pub nvos32_status: u32,
    /// `INFO`'s answer: the heap's total and free bytes.
    pub nvos32_total: u32,
    pub nvos32_free: u32,
    /// `INFO`'s block: the attributes asked about, and the largest free
    /// region's offset and size, and the heap's base.
    pub nvos32_info_attr: u32,
    pub nvos32_info_offset: u32,
    pub nvos32_info_size: u32,
    pub nvos32_info_base: u32,
    pub nvos32_fn_alloc_size: u32,
    pub nvos32_fn_alloc_tiled_pitch_height: u32,
    pub nvos32_fn_alloc_size_range: u32,
    pub nvos32_fn_free: u32,
    pub nvos32_fn_info: u32,
    pub nvos32_fn_hw_alloc: u32,
    pub nvos32_fn_hw_free: u32,
    pub nvos32_alloc_size: Alloc,
    pub nvos32_alloc_tiled_pitch_height: Alloc,
    pub nvos32_alloc_size_range: Alloc,
    /// `sizeof(NV_MEMORY_ALLOCATION_PARAMS)`, and its fields.
    pub mem_alloc_size: u32,
    pub mem_alloc: Alloc,
    /// `NVOS32_ATTR_LOCATION` as (low bit, high bit) of `attr`, and the value
    /// that means video memory.
    pub attr_location: (u32, u32),
    pub attr_location_vidmem: u32,
    pub alloc_flags_virtual: u32,
}

impl Layout {
    /// Whether an allocation's `attr` and `flags` take video memory: located
    /// in video memory, and not a virtual allocation with no backing.
    pub fn takes_vidmem(&self, attr: u32, flags: u32) -> bool {
        let (lo, hi) = self.attr_location;
        let width = hi - lo + 1;
        let loc = (attr >> lo) & ((1u32 << width) - 1);
        loc == self.attr_location_vidmem && flags & self.alloc_flags_virtual == 0
    }

    /// The index for `name`, if this release has it.
    pub fn index(&self, name: &str) -> Option<u32> {
        self.fb_info
            .iter()
            .find(|i| i.name == name)
            .map(|i| i.index)
    }

    /// The role of FB_INFO index `index`, if it reports memory.
    pub fn role(&self, index: u32) -> Option<Role> {
        self.fb_info
            .iter()
            .find(|i| i.index == index)
            .map(|i| i.role)
    }
}

/// The layout for a host release, and whether it is that release's own.
#[derive(Clone, Copy, Debug)]
pub struct Selected {
    pub layout: &'static Layout,
    pub exact: bool,
}

/// Profiles in ascending version order.
static PROFILES: &[(DriverVersion, &Layout)] = &[
    (DriverVersion::new(535, 129, 3), &v535_129_03::LAYOUT),
    (DriverVersion::new(580, 178, 4), &v580_178_04::LAYOUT),
    (DriverVersion::new(595, 71, 5), &v595_71_05::LAYOUT),
    (DriverVersion::new(595, 104, 2), &v595_104_02::LAYOUT),
    (DriverVersion::new(615, 71, 9), &v615_71_09::LAYOUT),
];

/// The layout for `v`: its own, or the nearest older release's.
pub fn select(v: DriverVersion) -> Option<Selected> {
    PROFILES
        .iter()
        .rev()
        .find(|(pv, _)| *pv <= v)
        .map(|(pv, l)| Selected {
            layout: l,
            exact: *pv == v,
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn all() -> impl Iterator<Item = (DriverVersion, &'static Layout)> {
        PROFILES.iter().copied()
    }

    #[test]
    fn profiles_are_in_ascending_order() {
        assert!(PROFILES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    /// Two names on one index would have a clamp write one field twice.
    #[test]
    fn no_two_memory_indices_share_a_number() {
        for (v, l) in all() {
            let mut seen = std::collections::HashSet::new();
            for i in l.fb_info {
                assert!(seen.insert(i.index), "{v}: index {:#x} twice", i.index);
            }
        }
    }

    /// What a clamp cannot do without: every release has to say how much
    /// there is and how much is free.
    #[test]
    fn every_release_reports_a_total_and_a_free() {
        for (v, l) in all() {
            for name in ["HEAP_SIZE", "TOTAL_RAM_SIZE", "RAM_SIZE", "HEAP_FREE"] {
                assert!(l.index(name).is_some(), "{v}: no {name}");
            }
        }
    }

    #[test]
    fn a_classified_index_is_either_present_or_named_absent() {
        let names = |l: &Layout| l.fb_info.iter().map(|i| i.name).collect::<Vec<_>>();
        let first = names(PROFILES[0].1).len() + PROFILES[0].1.fb_absent.len();
        for (v, l) in all() {
            assert_eq!(names(l).len() + l.fb_absent.len(), first, "{v}");
            for a in l.fb_absent {
                assert!(l.index(a).is_none(), "{v}: {a} both present and absent");
            }
        }
    }

    /// HEAP_RECLAIMABLE is the index the fork found moving. Here it arrives
    /// with 595.104.02, and earlier releases must say it is absent rather
    /// than leave a clamp to guess.
    #[test]
    fn heap_reclaimable_is_absent_before_595_104() {
        for (v, l) in all() {
            let has = l.index("HEAP_RECLAIMABLE").is_some();
            assert_eq!(has, v >= DriverVersion::new(595, 104, 2), "{v}");
        }
    }

    /// V2's list is inline, so its block is the count and the full list.
    #[test]
    fn the_v2_block_is_its_count_and_its_whole_list() {
        for (v, l) in all() {
            let b = l.fb_get_info_v2;
            assert_eq!(
                b.size,
                b.list + l.fb_info_max_list * l.fb_info_entry_size,
                "{v}"
            );
        }
    }

    #[test]
    fn the_two_spellings_are_the_ones_rm_names() {
        for (v, l) in all() {
            assert_eq!(l.cmd_fb_get_info, 0x2080_1301, "{v}");
            assert_eq!(l.cmd_fb_get_info_v2, 0x2080_1303, "{v}");
        }
    }

    #[test]
    fn video_memory_is_told_from_system_and_virtual() {
        let l = &v615_71_09::LAYOUT;
        let (lo, _) = l.attr_location;
        assert!(l.takes_vidmem(l.attr_location_vidmem << lo, 0));
        assert!(!l.takes_vidmem(1 << lo, 0), "PCI, system memory");
        assert!(!l.takes_vidmem(0, l.alloc_flags_virtual));
    }

    #[test]
    fn a_release_between_profiles_gets_the_older_one_inexactly() {
        let s = select(DriverVersion::new(600, 0, 0)).expect("a profile");
        assert!(!s.exact);
        assert!(std::ptr::eq(s.layout, &v595_104_02::LAYOUT));
        assert!(select(DriverVersion::new(615, 71, 9)).unwrap().exact);
        assert!(select(DriverVersion::new(500, 0, 0)).is_none());
    }
}

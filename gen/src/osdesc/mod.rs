//! The three routes by which a guest can name memory by a CPU address.
//!
//! RM lets a caller hand it an address and say "this memory is mine, map it
//! for the GPU". In a VM that is the sharpest edge in the whole interface. The
//! address the guest writes is an address in the *guest's* process; the
//! address RM reads is one in the backend's. Forwarded untouched, a guest
//! picks any address it likes and the host's RM pins and maps whatever of the
//! backend's memory lives there.
//!
//! There are three routes, which is the reason this is a table and not a
//! constant:
//!
//! - `NV_ESC_RM_ALLOC` with `hClass` = `NV01_MEMORY_SYSTEM_OS_DESCRIPTOR`,
//!   parameters `NV_OS_DESC_MEMORY_ALLOCATION_PARAMS`.
//! - `NV_ESC_RM_ALLOC_MEMORY` with the same class, parameters
//!   `NVOS02_PARAMETERS` -- the address in a different place.
//! - `NV_ESC_RM_VID_HEAP_CONTROL`, where the parameters are a union and the
//!   address is only there when `function` is `ALLOC_OS_DESCRIPTOR`.
//!
//! Generated by `gen/osdesc_extract.py`. Every offset is an `offsetof`, which
//! is not fussiness: `NV_OS_DESC_MEMORY_ALLOCATION_PARAMS` opens with four
//! `NvU32`s and the address is at byte 16, not 8, because `NvP64` carries
//! `NV_ALIGN_BYTES(8)`.

pub mod v535_129_03;
pub mod v580_178_04;
pub mod v595_104_02;
pub mod v595_71_05;
pub mod v615_71_09;

use crate::version::DriverVersion;

/// Where one route keeps its address.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Route {
    /// `sizeof` the parameter block this route carries.
    pub params_size: usize,
    /// Byte offset of the `NvP64` address.
    pub address_at: usize,
    /// Byte offset of the `NvU64` length. RM calls it `limit`, and it is the
    /// length minus one, not the length.
    pub limit_at: usize,
    /// Byte offset of the `NvU32` descriptor type, or `usize::MAX` where the
    /// route has none -- `NVOS02_PARAMETERS` carries no type, because the
    /// class it is allocating already said what the address is.
    pub type_at: usize,
}

impl Route {
    /// The address, if the block is long enough to hold one.
    pub fn address(&self, p: &[u8]) -> Option<u64> {
        read_u64(p, self.address_at)
    }

    /// The length RM will pin, in bytes. `limit` is the last byte's offset, so
    /// a one-page registration carries 4095 and means 4096.
    pub fn length(&self, p: &[u8]) -> Option<u64> {
        read_u64(p, self.limit_at)?.checked_add(1)
    }

    /// The descriptor type, where the route has one.
    pub fn desc_type(&self, p: &[u8]) -> Option<u32> {
        if self.type_at == usize::MAX {
            return None;
        }
        read_u32(p, self.type_at)
    }
}

fn read_u64(p: &[u8], at: usize) -> Option<u64> {
    p.get(at..at + 8)
        .map(|b| u64::from_le_bytes(b.try_into().unwrap()))
}

fn read_u32(p: &[u8], at: usize) -> Option<u32> {
    p.get(at..at + 4)
        .map(|b| u32::from_le_bytes(b.try_into().unwrap()))
}

/// One `NVOS32_DESCRIPTOR_TYPE_*`, so a refusal can say which was asked for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DescType {
    pub value: u32,
    pub name: &'static str,
}

impl DescType {
    pub const fn new(value: u32, name: &'static str) -> Self {
        Self { value, name }
    }
}

/// What one release says about registration by address.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct OsDesc {
    /// `NV01_MEMORY_SYSTEM_OS_DESCRIPTOR`.
    pub class: u32,
    /// `NVOS32_DESCRIPTOR_TYPE_VIRTUAL_ADDRESS`: the only type that is a user
    /// address at all. The rest name a kernel address, a file handle, a
    /// dma-buf or a scatter-gather table -- none of which a guest holds and
    /// none of which this backend can translate.
    pub virtual_address: u32,
    /// `NVOS32_FUNCTION_ALLOC_OS_DESCRIPTOR`.
    pub vid_heap_function: u32,
    pub alloc: Route,
    pub alloc_memory: Route,
    /// Byte offset of `hClass` in `NVOS02_PARAMETERS`: that route carries the
    /// class in its parameters rather than beside them.
    pub alloc_memory_class_at: usize,
    /// Byte offset of `status` in `NVOS32_PARAMETERS`.
    pub alloc_memory_status_at: usize,
    pub vid_heap: Route,
    /// Byte offset of `function` in `NVOS32_PARAMETERS`. Until it is read,
    /// nothing says whether the block holds an address at all.
    pub vid_heap_function_at: usize,
    /// Byte offset of `status` in `NVOS32_PARAMETERS`. A refusal is written
    /// here, which is what RM itself does for a function it does not serve
    /// (`rmapi_deprecated_vidheapctrl.c`: `pArgs->status = status`).
    pub vid_heap_status_at: usize,
    pub types: &'static [DescType],
}

impl OsDesc {
    /// The name of a descriptor type, for a refusal that says what was asked.
    pub fn type_name(&self, value: u32) -> Option<&'static str> {
        self.types.iter().find(|t| t.value == value).map(|t| t.name)
    }

    /// Whether a `VID_HEAP_CONTROL` block is the one that names an address.
    ///
    /// Every other function of that ioctl is an ordinary heap operation and
    /// carries no address, so reading one out of it would read whatever the
    /// union holds instead.
    pub fn vid_heap_registers_address(&self, p: &[u8]) -> bool {
        read_u32(p, self.vid_heap_function_at) == Some(self.vid_heap_function)
    }
}

struct Profile {
    version: DriverVersion,
    osdesc: fn() -> OsDesc,
}

/// Profiles in ascending version order.
static PROFILES: &[Profile] = &[
    Profile {
        version: DriverVersion::new(535, 129, 3),
        osdesc: || v535_129_03::OSDESC,
    },
    Profile {
        version: DriverVersion::new(580, 178, 4),
        osdesc: || v580_178_04::OSDESC,
    },
    Profile {
        version: DriverVersion::new(595, 71, 5),
        osdesc: || v595_71_05::OSDESC,
    },
    Profile {
        version: DriverVersion::new(595, 104, 2),
        osdesc: || v595_104_02::OSDESC,
    },
    Profile {
        version: DriverVersion::new(615, 71, 9),
        osdesc: || v615_71_09::OSDESC,
    },
];

/// What one host release says, or the nearest older one's.
///
/// Unlike the other tables there is no `exact` flag here, and no need for one:
/// every release describes these three routes identically, which
/// `the_releases_agree_about_where_an_address_is` holds them to. If one ever
/// stops, that test fails rather than a guest's address being read from the
/// wrong offset.
pub fn select(v: DriverVersion) -> Option<OsDesc> {
    PROFILES
        .iter()
        .rev()
        .find(|p| p.version <= v)
        .map(|p| (p.osdesc)())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_releases_agree_about_where_an_address_is() {
        let first = (PROFILES[0].osdesc)();
        for p in PROFILES {
            assert_eq!(
                (p.osdesc)(),
                first,
                "{} describes registration by address differently",
                p.version
            );
        }
    }

    /// Reading the address out of a block shorter than the release's own would
    /// read whatever follows it, so every route refuses to.
    #[test]
    fn an_address_is_only_read_from_a_block_long_enough_to_hold_one() {
        let d = (PROFILES[0].osdesc)();
        for r in [d.alloc, d.alloc_memory, d.vid_heap] {
            assert!(r.address_at + 8 <= r.params_size);
            assert!(r.limit_at + 8 <= r.params_size);
            let full = vec![0u8; r.params_size];
            assert_eq!(r.address(&full), Some(0));
            let short = vec![0u8; r.address_at + 7];
            assert_eq!(r.address(&short), None);
        }
    }

    /// `limit` is the last byte's offset, not the length. Off by one here is
    /// a page short of what RM pins.
    #[test]
    fn a_limit_is_one_less_than_the_length() {
        let d = (PROFILES[0].osdesc)();
        let mut p = vec![0u8; d.alloc.params_size];
        p[d.alloc.limit_at..d.alloc.limit_at + 8].copy_from_slice(&4095u64.to_le_bytes());
        assert_eq!(d.alloc.length(&p), Some(4096));

        // And a limit of u64::MAX has no length at all rather than wrapping to
        // zero, which would otherwise read as "register nothing".
        p[d.alloc.limit_at..d.alloc.limit_at + 8].copy_from_slice(&u64::MAX.to_le_bytes());
        assert_eq!(d.alloc.length(&p), None);
    }

    /// The union is only an address when `function` says so. Every other
    /// function is an ordinary heap operation whose bytes at that offset are
    /// something else entirely.
    #[test]
    fn a_heap_call_is_only_a_registration_when_its_function_says_so() {
        let d = (PROFILES[0].osdesc)();
        let mut p = vec![0u8; d.vid_heap.params_size];
        assert!(!d.vid_heap_registers_address(&p));
        let at = d.vid_heap_function_at;
        p[at..at + 4].copy_from_slice(&d.vid_heap_function.to_le_bytes());
        assert!(d.vid_heap_registers_address(&p));
    }

    #[test]
    fn every_descriptor_type_has_a_name_to_refuse_it_by() {
        let d = (PROFILES[0].osdesc)();
        assert_eq!(
            d.type_name(d.virtual_address),
            Some("NVOS32_DESCRIPTOR_TYPE_VIRTUAL_ADDRESS")
        );
        assert!(d.types.len() >= 8, "{} types", d.types.len());
        assert_eq!(d.type_name(0xdead), None);
    }

    #[test]
    fn a_release_older_than_every_table_has_none() {
        assert!(select(DriverVersion::new(470, 0, 0)).is_none());
        assert!(select(DriverVersion::new(615, 71, 9)).is_some());
        // Nearest-older, as everywhere else.
        assert_eq!(
            select(DriverVersion::new(600, 0, 0)),
            Some(v580_178_04::OSDESC)
        );
    }
}

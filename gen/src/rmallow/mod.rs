use crate::version::DriverVersion;

/// One control RM exports to an unprivileged caller.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AllowCtrl {
    pub cmd: u32,
    /// `sizeof` the parameter struct, from a probe compiled against the
    /// release's headers. Zero for a control that takes no parameters.
    pub params_size: u32,
}

impl AllowCtrl {
    pub const fn new(cmd: u32, params_size: u32) -> Self {
        Self { cmd, params_size }
    }
}

/// One class RM lets an unprivileged caller allocate.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AllowClass {
    pub class_id: u32,
    /// `sizeof` the allocation parameter struct; zero for `RS_NONE`.
    pub params_size: u32,
    /// `RS_REQUIRED` rather than `RS_OPTIONAL`: the allocation parameters have
    /// to be there.
    pub params_required: bool,
}

impl AllowClass {
    pub const fn new(class_id: u32, params_size: u32, params_required: bool) -> Self {
        Self {
            class_id,
            params_size,
            params_required,
        }
    }
}

/// One command RM rewrites into a modern one before anything else sees it.
///
/// `_nv04ControlWithSecInfo` consults RM's deprecated table first and only
/// falls through to the resource server if it misses, so a hit here is final
/// in RM and final here too. The converter reissues the call with the caller's
/// own security info, which is why `allowed` is the *modern* command's
/// privilege -- and why `params_size` is the *old* struct's, since that is
/// what the guest sends.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DeprecCtrl {
    pub cmd: u32,
    pub params_size: u32,
    pub allowed: bool,
}

impl DeprecCtrl {
    pub const fn new(cmd: u32, params_size: u32, allowed: bool) -> Self {
        Self {
            cmd,
            params_size,
            allowed,
        }
    }
}

/// A class whose control entry point forwards whatever it is handed.
///
/// `binapiControl` passes the command and the parameter block to GSP without
/// an exported-method entry, so there is no control flag for anything sent to
/// one. The privilege is the class's instead, and RM says it by having two
/// classes: `NV2081_BINAPI` non-privileged, `NV2082_BINAPI_PRIVILEGED` not.
/// Only a class the class table already permits gets a range here.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AllowRange {
    pub class_id: u32,
}

impl AllowRange {
    pub const fn new(class_id: u32) -> Self {
        Self { class_id }
    }

    /// Commands are numbered with their class in the high half.
    pub const fn holds(&self, cmd: u32) -> bool {
        cmd >> 16 == self.class_id
    }
}

/// RM's rule for the commands it no longer implements and forwards to GSP.
///
/// There are no flags for these anywhere; the rule is in the command number.
/// `RmGssLegacyRpcCmd` refuses a non-root caller any command matching
/// `privileged` in full, and forwards the rest to firmware unread -- so there
/// is no parameter size to check, only the ceiling RM applies.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct GssRule {
    pub mask: u32,
    pub privileged: u32,
    pub max_params: u32,
}

impl GssRule {
    pub const fn new(mask: u32, privileged: u32, max_params: u32) -> Self {
        Self {
            mask,
            privileged,
            max_params,
        }
    }

    /// Whether RM takes the GSP branch for this command at all.
    pub const fn holds(&self, cmd: u32) -> bool {
        cmd & self.mask != 0
    }

    /// RM's own test, copied: the privileged bits set in full means root.
    pub const fn needs_root(&self, cmd: u32) -> bool {
        cmd & self.privileged == self.privileged
    }
}

/// What the rule says about a command, when it says yes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CtrlAllow {
    /// RM sizes this from its own descriptor, so the block must be exact.
    Exact(u32),
    /// RM forwards this without reading it and only caps it. There is no
    /// size to require, so the backend requires no more than RM does.
    UpTo(u32),
}

/// Controls refused under every cap, whatever RM says about them.
///
/// RM marks all of these non-privileged, and for RM's own purposes that is
/// right: on a normal machine they tell a local user about the machine they
/// are already on. Here the machine is the host, and the caller is a guest, so
/// the same answers are a different thing entirely.
///
/// Verified present and non-privileged in all five release tables, which is
/// why this list is checked before the table and not after it.
pub static DENY: &[(u32, &str)] = &[
    // The host's process list, through the GPU. GET_PIDS returns the pids of
    // every process on the host with the GPU open; GET_PID_INFO then returns
    // per-process detail for one of them.
    (0x2080018d, "NV2080_CTRL_CMD_GPU_GET_PIDS"),
    (0x2080018e, "NV2080_CTRL_CMD_GPU_GET_PID_INFO"),
    // GPU accounting: whether it is on, which pids it has recorded, and what
    // it recorded about them. The matching setters are privileged in RM
    // already; these three reads are not.
    (0x00000b02, "NV0000_CTRL_CMD_GPUACCT_GET_ACCOUNTING_STATE"),
    (
        0x00000b03,
        "NV0000_CTRL_CMD_GPUACCT_GET_PROC_ACCOUNTING_INFO",
    ),
    (0x00000b04, "NV0000_CTRL_CMD_GPUACCT_GET_ACCOUNTING_PIDS"),
    (
        0x00000b06,
        "NV0000_CTRL_CMD_GPUACCT_GET_PROC_ACCOUNTING_INFO_V2",
    ),
    // Sub-process identity. SET_SUB_PROCESS_ID lets the caller name itself
    // something else inside the backend's client; DISABLE_..._USERD_ISOLATION
    // turns off the separation that identity buys. A guest does not get to
    // switch off an isolation mechanism on the host.
    (0x00000901, "NV0000_CTRL_CMD_SET_SUB_PROCESS_ID"),
    (
        0x00000902,
        "NV0000_CTRL_CMD_DISABLE_SUB_PROCESS_USERD_ISOLATION",
    ),
];

/// Whether this control is refused regardless of table and cap.
pub fn denied(cmd: u32) -> Option<&'static str> {
    DENY.iter().find(|(c, _)| *c == cmd).map(|(_, n)| *n)
}

struct Profile {
    version: DriverVersion,
    /// Functions rather than the slices themselves, for the reason given in
    /// [`crate::rmctrl`]: a static read in another static's initializer is
    /// const-evaluated and the table can end up copied per use.
    ctrl: fn() -> &'static [AllowCtrl],
    class: fn() -> &'static [AllowClass],
    deprec: fn() -> &'static [DeprecCtrl],
    catch_all: fn() -> &'static [AllowRange],
    gss: fn() -> GssRule,
}


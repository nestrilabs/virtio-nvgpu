//! The RM controls and classes a guest may ask for.
//!
//! RM decides for itself which of its entry points an unprivileged caller may
//! reach: every exported control method carries a flags word in the
//! NVOC-generated tables, and every allocatable class carries one in
//! `resource_list.h`. The tables here are that decision, per release.
//!
//! Through this project the caller RM checks is the *backend*, which runs as a
//! service account on the host and not as the guest. A control RM would have
//! refused to the guest's own uid it will run for the backend without
//! complaint. So the backend applies RM's rule itself, before forwarding, and
//! these tables are what it applies.
//!
//! Generated by `gen/rmallow_extract.py`, which reads each release's own
//! headers and compiles a probe against them. Nothing here is transcribed.
//!
//! # The shape of the rule
//!
//! A command passes only if it is in the selected table, its parameter block
//! is exactly the size the table gives, its pointers are described
//! ([`crate::rmctrl`]) or it has none, and its cap is on. A class passes only
//! if it is in the table and its allocation parameters match. Anything else is
//! refused.
//!
//! Note what the rule never does: it never asks whether a privileged bit is
//! *clear*. `RMCTRL_FLAGS_KERNEL_PRIVILEGED` and `RS_FLAGS_NONE` are both
//! zero, so an entry with no bits set is the most privileged thing in RM's
//! table, not the least. The generator tests for the non-privileged bit being
//! set, and so does everything here.

pub mod v535_129_03;
pub mod v580_178_04;
pub mod v595_104_02;
pub mod v595_71_05;
pub mod v615_71_09;

use crate::version::DriverVersion;

/// One control RM exports to an unprivileged caller.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AllowCtrl {
    pub cmd: u32,
    /// `sizeof` the parameter struct, from a probe compiled against the
    /// release's headers. Zero for a control that takes no parameters.
    pub params_size: u32,
}

impl AllowCtrl {
    pub const fn new(cmd: u32, params_size: u32) -> Self {
        Self { cmd, params_size }
    }
}

/// One class RM lets an unprivileged caller allocate.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AllowClass {
    pub class_id: u32,
    /// `sizeof` the allocation parameter struct; zero for `RS_NONE`.
    pub params_size: u32,
    /// `RS_REQUIRED` rather than `RS_OPTIONAL`: the allocation parameters have
    /// to be there.
    pub params_required: bool,
}

impl AllowClass {
    pub const fn new(class_id: u32, params_size: u32, params_required: bool) -> Self {
        Self {
            class_id,
            params_size,
            params_required,
        }
    }
}

/// Controls refused under every cap, whatever RM says about them.
///
/// RM marks all of these non-privileged, and for RM's own purposes that is
/// right: on a normal machine they tell a local user about the machine they
/// are already on. Here the machine is the host, and the caller is a guest, so
/// the same answers are a different thing entirely.
///
/// Verified present and non-privileged in all five release tables, which is
/// why this list is checked before the table and not after it.
pub static DENY: &[(u32, &str)] = &[
    // The host's process list, through the GPU. GET_PIDS returns the pids of
    // every process on the host with the GPU open; GET_PID_INFO then returns
    // per-process detail for one of them.
    (0x2080018d, "NV2080_CTRL_CMD_GPU_GET_PIDS"),
    (0x2080018e, "NV2080_CTRL_CMD_GPU_GET_PID_INFO"),
    // GPU accounting: whether it is on, which pids it has recorded, and what
    // it recorded about them. The matching setters are privileged in RM
    // already; these three reads are not.
    (0x00000b02, "NV0000_CTRL_CMD_GPUACCT_GET_ACCOUNTING_STATE"),
    (
        0x00000b03,
        "NV0000_CTRL_CMD_GPUACCT_GET_PROC_ACCOUNTING_INFO",
    ),
    (0x00000b04, "NV0000_CTRL_CMD_GPUACCT_GET_ACCOUNTING_PIDS"),
    (
        0x00000b06,
        "NV0000_CTRL_CMD_GPUACCT_GET_PROC_ACCOUNTING_INFO_V2",
    ),
    // Sub-process identity. SET_SUB_PROCESS_ID lets the caller name itself
    // something else inside the backend's client; DISABLE_..._USERD_ISOLATION
    // turns off the separation that identity buys. A guest does not get to
    // switch off an isolation mechanism on the host.
    (0x00000901, "NV0000_CTRL_CMD_SET_SUB_PROCESS_ID"),
    (
        0x00000902,
        "NV0000_CTRL_CMD_DISABLE_SUB_PROCESS_USERD_ISOLATION",
    ),
];

/// Whether this control is refused regardless of table and cap.
pub fn denied(cmd: u32) -> Option<&'static str> {
    DENY.iter().find(|(c, _)| *c == cmd).map(|(_, n)| *n)
}

struct Profile {
    version: DriverVersion,
    /// Functions rather than the slices themselves, for the reason given in
    /// [`crate::rmctrl`]: a static read in another static's initializer is
    /// const-evaluated and the table can end up copied per use.
    ctrl: fn() -> &'static [AllowCtrl],
    class: fn() -> &'static [AllowClass],
}

/// Profiles in ascending version order.
static PROFILES: &[Profile] = &[
    Profile {
        version: DriverVersion::new(535, 129, 3),
        ctrl: || v535_129_03::CTRL,
        class: || v535_129_03::CLASS,
    },
    Profile {
        version: DriverVersion::new(580, 178, 4),
        ctrl: || v580_178_04::CTRL,
        class: || v580_178_04::CLASS,
    },
    Profile {
        version: DriverVersion::new(595, 71, 5),
        ctrl: || v595_71_05::CTRL,
        class: || v595_71_05::CLASS,
    },
    Profile {
        version: DriverVersion::new(595, 104, 2),
        ctrl: || v595_104_02::CTRL,
        class: || v595_104_02::CLASS,
    },
    Profile {
        version: DriverVersion::new(615, 71, 9),
        ctrl: || v615_71_09::CTRL,
        class: || v615_71_09::CLASS,
    },
];

/// The allowlist for one host release.
#[derive(Clone, Copy)]
pub struct Selected {
    pub ctrl: &'static [AllowCtrl],
    pub class: &'static [AllowClass],
    /// The host release has tables of its own. When false these are an older
    /// release's, and what they permit for a newer release is an assumption.
    pub exact: bool,
}

/// The tables for a host driver version: its own, or the nearest older ones.
///
/// For an allowlist, nearest-older is already safe in one direction -- a
/// control a newer release added is absent here and so refused. The other
/// direction is the live one: a release can take a control that *was*
/// non-privileged and make it privileged, and an older table would still
/// permit it. [`Selected::ctrl_entry`] closes that by requiring every release
/// to agree whenever the table is not the host's own.
pub fn select(v: DriverVersion) -> Option<Selected> {
    PROFILES
        .iter()
        .rev()
        .find(|p| p.version <= v)
        .map(|p| Selected {
            ctrl: (p.ctrl)(),
            class: (p.class)(),
            exact: p.version == v,
        })
}

fn find_ctrl(table: &'static [AllowCtrl], cmd: u32) -> Option<&'static AllowCtrl> {
    table
        .binary_search_by_key(&cmd, |e| e.cmd)
        .ok()
        .map(|i| &table[i])
}

fn find_class(table: &'static [AllowClass], class_id: u32) -> Option<&'static AllowClass> {
    table
        .binary_search_by_key(&class_id, |e| e.class_id)
        .ok()
        .map(|i| &table[i])
}

impl Selected {
    /// The entry permitting this control, if every table that has to agree
    /// does.
    ///
    /// On an exact table this is a lookup. On an older one it is a lookup in
    /// each release: the control has to be non-privileged in all of them, at
    /// the same parameter size, or the backend is permitting on the strength
    /// of a table that does not describe the driver it is talking to.
    pub fn ctrl_entry(&self, cmd: u32) -> Option<&'static AllowCtrl> {
        if denied(cmd).is_some() {
            return None;
        }
        let e = find_ctrl(self.ctrl, cmd)?;
        if self.exact {
            return Some(e);
        }
        PROFILES
            .iter()
            .all(|p| find_ctrl((p.ctrl)(), cmd).is_some_and(|o| o.params_size == e.params_size))
            .then_some(e)
    }

    /// The entry permitting this class, under the same rule.
    pub fn class_entry(&self, class_id: u32) -> Option<&'static AllowClass> {
        let e = find_class(self.class, class_id)?;
        if self.exact {
            return Some(e);
        }
        PROFILES
            .iter()
            .all(|p| find_class((p.class)(), class_id).is_some_and(|o| o == e))
            .then_some(e)
    }
}

/// The versions with tables of their own, ascending.
pub fn supported_versions() -> impl Iterator<Item = DriverVersion> {
    PROFILES.iter().map(|p| p.version)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn v(a: u32, b: u32, c: u32) -> DriverVersion {
        DriverVersion::new(a, b, c)
    }

    #[test]
    fn tables_are_sorted_and_unique() {
        for p in PROFILES {
            let t = (p.ctrl)();
            assert!(
                t.windows(2).all(|w| w[0].cmd < w[1].cmd),
                "{} ctrl",
                p.version
            );
            let c = (p.class)();
            assert!(
                c.windows(2).all(|w| w[0].class_id < w[1].class_id),
                "{} class",
                p.version
            );
        }
    }

    #[test]
    fn every_release_has_both_tables() {
        for p in PROFILES {
            assert!(!(p.ctrl)().is_empty(), "{} ctrl", p.version);
            assert!(!(p.class)().is_empty(), "{} class", p.version);
        }
    }

    /// The point of the whole file. RM marks each of these non-privileged, so
    /// without the deny list the allowlist would pass them.
    #[test]
    fn denied_controls_are_in_the_tables_and_still_refused() {
        for (cmd, name) in DENY {
            let found = PROFILES
                .iter()
                .any(|p| find_ctrl((p.ctrl)(), *cmd).is_some());
            assert!(found, "{name} is in no table; the deny entry is stale");
            let sel = select(v(615, 71, 9)).unwrap();
            assert!(
                sel.ctrl_entry(*cmd).is_none(),
                "{name} passed the allowlist"
            );
        }
    }

    #[test]
    fn an_exact_table_is_the_release_s_own() {
        let sel = select(v(615, 71, 9)).unwrap();
        assert!(sel.exact);
        assert!(std::ptr::eq(sel.ctrl, v615_71_09::CTRL));
        assert!(std::ptr::eq(sel.class, v615_71_09::CLASS));
    }

    #[test]
    fn an_unknown_release_falls_back_and_says_so() {
        let sel = select(v(615, 80, 0)).unwrap();
        assert!(!sel.exact);
        assert!(std::ptr::eq(sel.ctrl, v615_71_09::CTRL));
        assert!(select(v(500, 0, 0)).is_none());
    }

    /// On a fallback, a control only one release permits is refused: the
    /// backend would be permitting on the strength of a table that does not
    /// describe the host.
    #[test]
    fn a_fallback_needs_every_release_to_agree() {
        let only_newest = v615_71_09::CTRL
            .iter()
            .find(|e| {
                PROFILES
                    .iter()
                    .any(|p| find_ctrl((p.ctrl)(), e.cmd).is_none())
            })
            .expect("the releases differ somewhere");
        let exact = select(v(615, 71, 9)).unwrap();
        assert!(exact.ctrl_entry(only_newest.cmd).is_some());
        let fallback = select(v(615, 80, 0)).unwrap();
        assert!(fallback.ctrl_entry(only_newest.cmd).is_none());
    }

    /// A control every release agrees on survives the fallback, or the rule
    /// above would be refusing everything.
    #[test]
    fn a_fallback_still_permits_what_every_release_permits() {
        let common = v615_71_09::CTRL
            .iter()
            .find(|e| {
                PROFILES.iter().all(|p| {
                    find_ctrl((p.ctrl)(), e.cmd).is_some_and(|o| o.params_size == e.params_size)
                })
            })
            .expect("the releases agree somewhere");
        assert!(
            select(v(615, 80, 0))
                .unwrap()
                .ctrl_entry(common.cmd)
                .is_some()
        );
    }
}

"""NVKMS commands (class MODESET), one table per range of host driver versions.

The ioctl itself is always NVKMS_IOCTL_IOWR, _IOWR('m', 0, 16), whose
argument is struct NvKmsIoctlParams {u32 cmd; u32 size; u64 address}
(kernel-open/nvidia-modeset/nvkms-ioctl.h:38). An entry here is keyed by the
command inside, describes the params block `address` points at, and requires
`size` to equal that block's size (nvKmsIoctl refuses anything else,
src/nvidia-modeset/src/nvkms.c:5183). NVKMS copies in the request half and
out the reply half, the latter even when the command failed (5220-5243), which
is the RANGE copy-back.

The per-version tables are generated by the NVKMS workstream from offset
probes against each version's nvkms-api.h. What is here is only an example
that exercises the machinery end to end: a pointer-free, descriptor-free query
of 610.57.04, measured with nvkms-api.h from that release
(size 44, request 12 @0, reply 32 @12).
"""

from .lang import *

TABLES = [
    ModesetTable(
        'v610_57_04_example', (610, 57, 4), (610, 57, 4),
        probe_includes=[
            'src/nvidia-modeset/interface',
            'src/common/unix/common/inc',
            'src/common/inc',
            'src/common/sdk/nvidia/inc',
        ],
        probe_headers=['nvkms-api.h', 'nvkms-ioctl.h'],
        ioctls=[
            # EXAMPLE ENTRY, not a policy decision: NVKMS workstream replaces
            # this table with the generated one.
            NvkmsIoctl('QUERY_CONNECTOR_STATIC_DATA', 3,
                       'struct NvKmsQueryConnectorStaticDataParams', 44,
                       reply_off=12, reply_len=32),
        ]),
]
